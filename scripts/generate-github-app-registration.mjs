#!/usr/bin/env node
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const clientId = process.env.XOPC_BUILD_GITHUB_APP_CLIENT_ID?.trim() ?? '';
const slug = process.env.XOPC_BUILD_GITHUB_APP_SLUG?.trim() ?? '';

if (!clientId || !slug) {
  console.error(
    'GitHub App release registration is required. Set XOPC_BUILD_GITHUB_APP_CLIENT_ID and XOPC_BUILD_GITHUB_APP_SLUG.',
  );
  process.exit(1);
}
if (/\s/.test(clientId) || !/^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?$/i.test(slug)) {
  console.error('GitHub App client id or slug is invalid.');
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'generated', 'github-app-registration.ts');
writeFileSync(
  target,
  `// Generated by scripts/generate-github-app-registration.mjs.\n` +
    `export const GITHUB_APP_CLIENT_ID = ${JSON.stringify(clientId)};\n` +
    `export const GITHUB_APP_SLUG = ${JSON.stringify(slug)};\n`,
  'utf8',
);
