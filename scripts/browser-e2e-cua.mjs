// Execute through the Codex CUA REPL against the native host or an installed production app.
export async function* runNativeBrowserE2e(app, site) {
  const checks = [];
  const snapshot = () => app.getAXState({ emit: false, disableDiffing: true });
  const check = (name, condition) => { if (!condition) throw new Error(name); checks.push(name); };
  const click = async text => {
    const lines = (await snapshot()).split('\n').filter(l => /^\s*\d+ /.test(l) && l.includes(text));
    if (lines.length !== 1) throw new Error(`Expected exactly one native target: ${text}, found ${lines.length}`);
    await app.click(Number(lines[0].trim().split(' ')[0]));
    return snapshot();
  };
  const navigate = async path => {
    await click('Search or enter a URL'); await app.pressKey('super+a'); await app.paste(path.startsWith('/') ? site + path : path); await app.pressKey('Return'); return snapshot();
  };
  let state = await snapshot();
  if (state.includes('button Skip for now')) await click('button Skip for now');
  await click('toggle button Description: Open workspace tools');
  await click('button Files');
  await click('button New tab'); await click('button Browser');
  state = await navigate('/one');
  check('Native page and isolated preload', state.includes('Isolation: electronAPI=undefined, require=undefined, process=undefined'));
  await click('Description: Page draft,'); await app.paste('Native retained form');
  await click('link Description: Go to page two,');
  state = await snapshot(); check('Navigation updates title', state.includes('tab (selected) Page Two'));
  state = await click('button Browser back'); check('Back and form restoration', state.includes('Value: Native retained form'));
  state = await click('button Browser forward'); check('Forward', state.includes('tab (selected) Page Two'));
  await click('button Browser back'); state = await snapshot();
  const beforeVisits = Number(state.match(/text Visits: (\d+)/)?.[1]);
  state = await click('button Reload page'); check('Reload makes real request', Number(state.match(/text Visits: (\d+)/)?.[1]) > beforeVisits);
  await click('Description: Page draft,'); await app.paste('Keep across tool tabs');
  state = await click('link Description: Open page two in a new tab,');
  check('Popup becomes a new workspace tab', state.includes('tab (selected) Page Two') && state.includes('tab (settable, integer) Page One'));
  state = await click('tab (settable, integer) Page One,'); check('Independent tab form state', state.includes('Value: Keep across tool tabs'));
  state = await click('pop up button Chat menu'); check('DOM menu occludes native guest', state.includes('menu Chat menu') && !state.includes('HTML content Page One'));
  await app.pressKey('Escape'); await snapshot();
  yield [...checks];
  await click('tab (settable, integer) Files,'); state = await click('button report.md');
  check('Existing file preview', state.includes('heading Workspace E2E') && !state.includes('HTML content Page One'));
  await click('toggle button Description: Edit,'); await click('text entry area (settable) # Workspace E2E');
  await app.pressKey('super+a'); await app.paste('# Workspace E2E\n\nNative E2E file saved.\n');
  state = await click('tab (settable, integer) Page One,'); check('Browser stays alive across file edit', state.includes('Value: Keep across tool tabs'));
  await click('button New tab'); await click('button Side chat');
  await click('text entry area (settable) Type a message…'); await app.paste('Native sidechat draft');
  await click('tab (settable, integer) Page One,'); state = await click('tab (settable, integer) Side chat,');
  check('Sidechat draft retained', state.includes('Native sidechat draft'));
  await click('text entry area (settable) Description: Type a message…'); await app.pressKey('super+a'); await app.paste('E2E_SEND');
  await click('button Send'); state = await snapshot();
  check('Real sidechat response', state.includes('text E2E_SEND') && (state.match(/E2E_REPLY local model completed\./g)?.length ?? 0) >= 2);
  await click('text entry area (settable) Type a message…'); await app.paste('E2E_HOLD'); await click('button Send');
  state = await click('tab (settable, integer) Page One,'); check('Background sidechat state', state.includes('Side chat Running'));
  await click('tab (settable, integer) Side chat Running,'); state = await click('button Abort'); check('Sidechat abort', state.includes('text aborted') && !state.includes('button Abort'));
  yield [...checks];
  await click('tab (settable, integer) Page One,'); await click('link Description: Open slow page,'); state = await click('button Stop loading page');
  check('Browser stop loading', state.includes('button Reload page') && !state.includes('button Stop loading page'));
  state = await navigate('/fail'); check('Host failure UI', state.includes('Page could not be loaded') && state.includes('button Retry') && !state.includes('HTML content Slow page'));
  state = await navigate('/one'); check('Recover through address navigation', state.includes('HTML content Page One'));
  await click('button Protect unsaved page'); state = await click('button Close Page One');
  check('Native beforeunload dialog', state.includes('Leave this page?') && state.includes('button Stay'));
  state = await click('button Stay'); check('Cancel close keeps page', state.includes('Unsaved page protected') && state.includes('button Close Page One'));
  await click('button Close Page One'); state = await click('button Leave');
  check('Confirm close releases native page only', !state.includes('button Close Page One') && state.includes('button Close Page Two') && !state.includes('JavaScript error'));
  await click('tab (settable, integer) Page Two,');
  state = await click('button Request location'); check('Site permissions denied visibly', state.includes('Site permission blocked: geolocation') && state.includes('button Location denied'));
  await app.pressKey('super+l'); state = await snapshot(); check('Guest Cmd+L selects host URL', state.includes('Selected text:'));
  await app.paste('native browser search'); await app.pressKey('Return'); state = await snapshot();
  check('Search waits for explicit engine', state.includes('Choose where to send this search.') && !state.includes('HTML content Page Two'));
  await click('button Cancel'); state = await navigate('javascript:alert(1)');
  check('Unsafe protocols blocked', state.includes('Only HTTP and HTTPS addresses are supported') && state.includes('tab (selected) Page Two'));
  yield [...checks];
  state = await navigate('/two');
  state = await click('button Expand workspace'); check('Expand retains native content', state.includes('button Restore workspace') && state.includes('HTML content Page Two'));
  state = await click('button Restore workspace'); check('Restore retains native content', state.includes('button Expand workspace') && state.includes('HTML content Page Two'));
  state = await click('toggle button Description: Toggle file tree,');
  if (state.includes('button Close file tree')) {
    check('Tree overlay hides native guest', !state.includes('HTML content Page Two'));
    await app.pressKey('Escape'); await snapshot();
  } else await click('toggle button Description: Toggle file tree,');
  state = await click('button Description: Collapse workspace'); check('Collapse hides native content', !state.includes('HTML content Page Two'));
  await click('toggle button Description: Open workspace tools');
  state = await click('tab (settable, integer) Page Two,'); check('Reopen retains browser', state.includes('HTML content Page Two'));
  return checks;
}
