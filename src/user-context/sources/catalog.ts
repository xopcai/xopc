export function listUnderstandingSourceDefinitions(
  platform: Exclude<UnderstandingSourcePlatform, 'all'> = process.platform as Exclude<UnderstandingSourcePlatform, 'all'>,
): UnderstandingSourceDefinition[] {
  return [...LOCAL_TIER1_COMMON, ...(LOCAL_TIER2_PLATFORM[platform] ?? []), ...WORK_AND_CLOUD];
}

export function listLocalUnderstandingSourceDefinitions(
  platform: Exclude<UnderstandingSourcePlatform, 'all'> = process.platform as Exclude<UnderstandingSourcePlatform, 'all'>,
): UnderstandingSourceDefinition[] {
  return listUnderstandingSourceDefinitions(platform).filter((source) => isLocalUnderstandingSourceId(source.id));
}

export function getUnderstandingSourceDefinition(
  sourceId: string,
  platform: Exclude<UnderstandingSourcePlatform, 'all'> = process.platform as Exclude<UnderstandingSourcePlatform, 'all'>,
): UnderstandingSourceDefinition | undefined {
  return listUnderstandingSourceDefinitions(platform).find((source) => source.id === sourceId);
}
